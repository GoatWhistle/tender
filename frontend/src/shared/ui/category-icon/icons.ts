export function categoryIcon(code: string): icons.LucideIcon {
  const okpd = code.split("-")[0] ?? code
  for (let end = okpd.length; end > 0; end--) {
    const icon = prefixes[okpd.slice(0, end)]
    if (icon) return icon
  }
  return icons.Package
}
