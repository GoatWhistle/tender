import {
  ArrowLeft,
  ArrowRight,
  ArrowUp,
  Check,
  CheckCircle2,
  ChevronDown,
  ChevronRight,
  CircleAlert,
  Download,
  FileText,
  Globe,
  History,
  Info,
  ListFilter,
  LoaderCircle,
  MessageSquare,
  Moon,
  Pencil,
  Plus,
  Search,
  ShieldCheck,
  Sparkles,
  Sun,
  User,
  X,
} from "lucide-react"

const icons = {
  download: Download,
  back: ArrowLeft,
  next: ArrowRight,
  check: Check,
  close: X,
  success: CheckCircle2,
  expand: ChevronDown,
  chevron: ChevronRight,
  alert: CircleAlert,
  document: FileText,
  language: Globe,
  history: History,
  info: Info,
  rank: ListFilter,
  loading: LoaderCircle,
  message: MessageSquare,
  moon: Moon,
  edit: Pencil,
  plus: Plus,
  search: Search,
  send: ArrowUp,
  shield: ShieldCheck,
  spark: Sparkles,
  sun: Sun,
  user: User,
}
export type IconName = keyof typeof icons
export function Icon({ name, size = 18 }: { readonly name: IconName; readonly size?: number }) {
  const Component = icons[name]
  return <Component size={size} strokeWidth={1.7} aria-hidden="true" />
}
