ROOT=pathlib.Path(__file__).resolve().parents[2]
OUT=ROOT/'evals'/'datasets'/'smoke_v0.json'
P=JsonKtruSource(ROOT/'var'/'ktru.json').load()
groups={}
for p in P:
    if p.is_template or not p.parent: groups.setdefault(p.name,p)
G=list(groups.values())
vec=TfidfVectorizer(analyzer='char_wb',ngram_range=(3,5),sublinear_tf=True)
X=vec.fit_transform([f"{g.name} {g.name} {g.okpd2_name}".lower() for g in G])
def topk(t,k):
    sc=(vec.transform([t.lower()])@X.T).toarray()[0]
    return [G[i].name for i in sc.argsort()[::-1][:k]]
out={"groups":{g.name:g.okpd2_name for g in G},"cases":[],"attrs":[]}
for t,gold in CASES:
    out["cases"].append({"text":t,"gold":gold,"top20":topk(t,20)})
for t,gname,cname,gold in ATTRS:
    c=groups[gname].char(cname)
    assert c and gold in [v.text for v in c.values], (gname,cname)
    out["attrs"].append({"text":t,"group":gname,"char":cname,"options":[v.text for v in c.values],"gold":gold})
OUT.write_text(json.dumps(out,ensure_ascii=False,indent=1))
r={k:sum(any(g in c["top20"][:k] for g in c["gold"]) for c in out["cases"] if c["gold"]!=[NONE]) for k in (1,5,10,20)}
n=sum(c["gold"]!=[NONE] for c in out["cases"])
print("TF-IDF recall@k:",{k:f"{v}/{n}" for k,v in r.items()})
